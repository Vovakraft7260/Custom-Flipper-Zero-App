// Turns the Flipper .proto files into one JS module the app can load offline.
// Run with: npm run proto
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import protobuf from 'protobufjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const protoDir = join(root, 'proto');
const files = readdirSync(protoDir).filter((f) => f.endsWith('.proto')).map((f) => join(protoDir, f));

const pb = new protobuf.Root();
pb.loadSync(files, { keepCase: true });
pb.resolveAll();

const out = join(root, 'src', 'flipper', 'proto-bundle.js');
writeFileSync(
  out,
  '// Generated by scripts/build-proto.mjs from proto/*.proto. Do not edit.\n' +
    `export default ${JSON.stringify(pb.toJSON(), null, 0)};\n`,
);
console.log(`Wrote ${out}`);

// Builds src/remote/tv-codes.js from the TVs folder of Flipper-IRDB
// (https://github.com/Lucaslhm/Flipper-IRDB, CC0 1.0 public domain).
// Usage: node scripts/build-tv-remotes.mjs /path/to/Flipper-IRDB/TVs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseInfrared } from '../src/flipper/flipperformat.js';
import { BUTTONS } from '../src/remote/buttons.js';

const src = process.argv[2];
if (!src) throw new Error('Pass the path to Flipper-IRDB/TVs');
const MAX_SETS_PER_BRAND = 4;
const MIN_BUTTONS = 6;

const walk = (dir) =>
  readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : n.toLowerCase().endsWith('.ir') ? [p] : [];
  });

const norm = (name) => name.toLowerCase().replace(/\s+/g, '_').trim();

function toCodeSet(file) {
  const signals = parseInfrared(readFileSync(file, 'utf8').replace(/\r/g, ''));
  const keys = {};
  for (const b of BUTTONS) {
    const sig = signals.find((s) => b.match.some((m) => m === norm(s.name)));
    if (!sig) continue;
    if (sig.type === 'parsed' && sig.protocol && sig.address && sig.command) {
      keys[b.id] = { p: sig.protocol, a: sig.address, c: sig.command };
    } else if (sig.type === 'raw' && sig.data) {
      keys[b.id] = { f: Number(sig.frequency) || 38000, d: Number(sig.duty_cycle) || 0.33, r: sig.data };
    }
  }
  return keys;
}

const brands = [];
for (const brandDir of readdirSync(src).sort()) {
  const full = join(src, brandDir);
  if (!statSync(full).isDirectory()) continue;
  const sets = [];
  const seen = new Set();
  for (const file of walk(full)) {
    const keys = toCodeSet(file);
    const n = Object.keys(keys).length;
    if (n < MIN_BUTTONS || !keys.power) continue;
    const fp = JSON.stringify(keys.power) + JSON.stringify(keys.ok ?? '');
    if (seen.has(fp)) continue; // same remote saved twice
    seen.add(fp);
    sets.push({ from: basename(file, '.ir'), keys, n });
  }
  if (!sets.length) continue;
  // Prefer remotes that can navigate menus (OK + arrows), then the most buttons.
  const nav = (k) => ['ok', 'up', 'down', 'left', 'right'].filter((x) => k[x]).length;
  sets.sort((a, b) => nav(b.keys) - nav(a.keys) || b.n - a.n);
  brands.push({
    name: brandDir.replace(/_/g, ' '),
    files: walk(full).length,
    sets: sets.slice(0, MAX_SETS_PER_BRAND).map(({ from, keys }) => ({ from, keys })),
  });
}
brands.sort((a, b) => b.files - a.files || a.name.localeCompare(b.name));
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'remote', 'tv-codes.js');
writeFileSync(
  out,
  '// Generated by scripts/build-tv-remotes.mjs from Flipper-IRDB (CC0 1.0). Do not edit.\n' +
    `export default ${JSON.stringify(brands.map(({ name, sets }) => ({ name, sets })))};\n`,
);
console.log(`${brands.length} brands, ${brands.reduce((n, b) => n + b.sets.length, 0)} code sets -> ${out}`);
